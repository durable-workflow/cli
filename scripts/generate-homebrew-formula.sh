#!/usr/bin/env sh
# Generate a Homebrew formula for the macOS standalone binaries: arm64, plus
# Intel when the release carries dw-macos-x86_64 (2.5.0 and later).

set -eu

dist_dir="${1:-dist}"
tag="${2:-${GITHUB_REF_NAME:-}}"
asset="dw-macos-aarch64"
formula="$dist_dir/dw.rb"

err() {
    printf 'error: %s\n' "$*" >&2
    exit 1
}

[ -n "$tag" ] || err "release tag is required"
tag="${tag#v}"
[ -s "$dist_dir/$asset" ] || err "missing release asset: $dist_dir/$asset"

checksum() {
    if command -v sha256sum >/dev/null 2>&1; then
        sha256sum "$1" | awk '{print $1}'
    elif command -v shasum >/dev/null 2>&1; then
        shasum -a 256 "$1" | awk '{print $1}'
    else
        err "sha256sum or shasum is required"
    fi
}

sha256=$(checksum "$dist_dir/$asset")
version="$tag"
intel_asset="dw-macos-x86_64"

if [ -s "$dist_dir/$intel_asset" ]; then
    intel_sha256=$(checksum "$dist_dir/$intel_asset")
    cat > "$formula" <<FORMULA
# Generated by durable-workflow/cli release workflow.
class Dw < Formula
  desc "Command-line interface for Durable Workflow Server"
  homepage "https://durable-workflow.com"
  version "${version}"

  on_arm do
    url "https://github.com/durable-workflow/cli/releases/download/${tag}/${asset}"
    sha256 "${sha256}"
  end

  on_intel do
    url "https://github.com/durable-workflow/cli/releases/download/${tag}/${intel_asset}"
    sha256 "${intel_sha256}"
  end

  def install
    bin.install (Hardware::CPU.arm? ? "${asset}" : "${intel_asset}") => "dw"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/dw --version")
  end
end
FORMULA
    exit 0
fi

cat > "$formula" <<EOF
# Generated by durable-workflow/cli release workflow.
class Dw < Formula
  desc "Command-line interface for Durable Workflow Server"
  homepage "https://durable-workflow.com"
  url "https://github.com/durable-workflow/cli/releases/download/${tag}/${asset}"
  sha256 "${sha256}"
  version "${version}"

  def install
    bin.install "${asset}" => "dw"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/dw --version")
  end
end
EOF
